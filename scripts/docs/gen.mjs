#!/usr/bin/env node
// Generates the docs site's 🤖 MDX partials (apps/site/content/generated/**)
// from the engine's own sources, so the parameter and diagnostics tables can
// never drift from the code:
//   - spec/parameters.json        the parameter catalog (docs/parameters.md)
//   - spec/fx-spec-1.schema.json  the FX Spec key reference
//   - scripts/docs/diagnostics-cases.json, run live through packages/core
//     (resolveFxSpec / checkOverrides) so the table shows real messages
//
//   node scripts/docs/gen.mjs          write the partials
//   node scripts/docs/gen.mjs --check  exit 1 if any partial is stale
//
// Needs packages/core built (npm run build there) for the diagnostics.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = join(root, "apps/site/content/generated");
const check = process.argv.includes("--check");
const read = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const catalog = read("spec/parameters.json");
const schema = read("spec/fx-spec-1.schema.json");
const cases = read("scripts/docs/diagnostics-cases.json");
const { resolveFxSpec, checkOverrides } = await import(join(root, "packages/core/dist/index.js"));

const HEADER = (src) => `{/* 🤖 Generated by scripts/docs/gen.mjs from ${src}. Do not edit: run \`node scripts/docs/gen.mjs\`. */}\n\n`;

/** Text safe inside an MDX table cell. */
const esc = (s) =>
  String(s ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\{/g, "\\{")
    .replace(/\}/g, "\\}")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\n/g, " ");
const code = (s) => "`" + String(s).replace(/`/g, "") + "`";
const num = (x) => {
  if (x === null || x === undefined) return "";
  if (Array.isArray(x)) return x.length ? "[" + x.map(num).join(", ") + "]" : "[]";
  if (Math.abs(x) >= 1e6) return x > 0 ? "∞" : "−∞";
  return String(Math.round(x * 1e4) / 1e4);
};
const table = (head, rows) =>
  rows.length === 0
    ? "_None._\n"
    : `| ${head.join(" | ")} |\n|${head.map(() => "---").join("|")}|\n` + rows.map((r) => `| ${r.join(" | ")} |`).join("\n") + "\n";

const defs = catalog.definitions;
const cats = Object.fromEntries(catalog.categories.map((c) => [c.id, c.label]));

function typeCell(d) {
  if (d.type === "choice") return "choice: " + d.choices.map((c) => code(c.spec ?? c.value)).join(" · ");
  if (d.type === "number[]") return `number[] (${d.minItems}–${d.maxItems}${d.lengthFrom ? `, length = ${code(d.lengthFrom)}` : ""})`;
  return d.type;
}
function rangeCell(d) {
  if (d.type === "boolean" || d.type === "choice") return "";
  const valid = `${num(d.min)}–${num(d.max)}`;
  const ui = d.uiMin !== undefined && (d.uiMin !== d.min || d.uiMax !== d.max) ? ` (UI ${num(d.uiMin)}–${num(d.uiMax)})` : "";
  return valid + ui + (d.unit ? ` ${esc(d.unit)}` : "");
}
function defaultCell(dflt, sizes) {
  const vals = sizes.map((z) => dflt?.[z]);
  if (vals.every((v) => JSON.stringify(v) === JSON.stringify(vals[0]))) return num(vals[0]);
  return sizes.map((z, i) => `${z}: ${num(vals[i])}`).join(" · ");
}
function descCell(d) {
  let s = esc(d.description);
  if (d.if) s += ` _Only while ${code(d.if.key)} is ${d.if.in.join(" or ")}._`;
  if (d.aliases?.length) s += ` _Also accepted: ${d.aliases.map(code).join(", ")}._`;
  return s;
}

const files = new Map();

// ---- catalog/<object>.mdx
for (const obj of catalog.objects) {
  let s = HEADER("spec/parameters.json");
  s += `The ${esc(obj.label.toLowerCase())} component is ${code(obj.component)}. Pick a look with ${code("pattern")}; each pattern reads the props below. Sizes are engine sizes (20, 32, 64): defaults can differ per size.\n\n`;
  s += table(
    ["Pattern", "Mode", "Speed", "Values (app data)"],
    obj.patterns.map((p) => [
      `${esc(p.label)} (${code(p.id)})`,
      code(p.mode),
      num(p.speed) + "×",
      p.params.map((r) => defs[r.ref]).filter((d) => d.group === "value").map((d) => code(d.path)).join(", ") || "—",
    ]),
  );
  for (const p of obj.patterns) {
    const rows = (tier) =>
      p.params
        .map((r) => [defs[r.ref], r.default])
        .filter(([d]) => d.tier === tier)
        .map(([d, dflt]) => [code(d.path), esc(cats[d.category]), typeCell(d), rangeCell(d), defaultCell(dflt, p.sizes.map(String)), descCell(d)]);
    s += `\n### ${esc(p.label)} [#${p.id}]\n\n`; // Fumadocs custom heading id
    s += `${code(`pattern: "${p.id}"`)} · mode ${code(p.mode)} · speed ${num(p.speed)}× · sizes ${p.sizes.join(", ")}\n\n`;
    s += table(["Prop", "Category", "Type", "Range", "Default", "Description"], rows("basic"));
    const adv = rows("advanced");
    if (adv.length) {
      s += `\n<details>\n<summary>Advanced props (${adv.length})</summary>\n\n` + table(["Prop", "Category", "Type", "Range", "Default", "Description"], adv) + "\n</details>\n";
    }
  }
  files.set(`catalog/${obj.id}.mdx`, s);
}

// ---- values.mdx: every value-group definition, by object
{
  let s = HEADER("spec/parameters.json");
  const rows = [];
  for (const obj of catalog.objects) {
    const seen = new Map();
    for (const p of obj.patterns) {
      for (const r of p.params) {
        const d = defs[r.ref];
        if (d.group !== "value") continue;
        const k = r.ref;
        if (!seen.has(k)) seen.set(k, { d, patterns: [] });
        seen.get(k).patterns.push(p.id);
      }
    }
    for (const { d, patterns } of seen.values()) {
      rows.push([`${code(obj.component)}`, code(d.path), patterns.map(code).join(", "), typeCell(d), rangeCell(d), descCell(d)]);
    }
  }
  for (const i of catalog.runtimeInputs.filter((i) => i.group === "value")) {
    rows.push(["every object", code(i.path), "every pattern", i.type, i.min !== undefined ? `${num(i.min)}–${num(i.max)}` : "", esc(i.description)]);
  }
  s += table(["Component", "Prop", "Patterns", "Type", "Range", "Description"], rows);
  files.set("values.mdx", s);
}

// ---- materials/<id>.mdx
for (const m of catalog.materials) {
  let s = HEADER("spec/parameters.json");
  s += `${esc(m.description)} In an FX Spec: ${code(m.specSection)}. Off until ${code(defs[m.master].path)} is above 0.\n\n`;
  s += table(
    ["Prop", "FX Spec", "Type", "Range", "Default", "Description"],
    m.params.map((id) => defs[id]).map((d) => [code(d.path), code(d.specPath), typeCell(d), rangeCell(d), num(d.fallback), descCell(d)]),
  );
  if (["particles", "liquid"].includes(m.id)) {
    const keys = m.params.map((id) => defs[id]);
    const rows = [];
    for (const obj of catalog.objects) {
      for (const p of obj.patterns) {
        const md = p.materialDefaults?.[m.id] ?? {};
        const own = Object.entries(md).filter(([k]) => keys.some((d) => d.key === k));
        if (own.length && m.id === "liquid") rows.push([code(p.id), own.map(([k, v]) => `${code(keys.find((d) => d.key === k).path)} ${num(v)}`).join(" · ")]);
        if (m.id === "particles") {
          const style = keys.find((d) => d.key === "particleStyle");
          const differs = own.filter(([k, v]) => {
            const d = keys.find((x) => x.key === k);
            return d && v !== d.fallback;
          });
          if (differs.length) rows.push([code(p.id), differs.map(([k, v]) => {
            const d = keys.find((x) => x.key === k);
            const val = d === style ? d.choices.find((c) => c.value === v)?.spec ?? v : num(v);
            return `${code(d.path)} ${val}`;
          }).join(" · ")]);
        }
      }
    }
    s += `\n**Per-pattern defaults** (applied only while the material is on, and only to props you leave unset):\n\n` + table(["Pattern", "Defaults"], rows);
  }
  files.set(`materials/${m.id}.mdx`, s);
}

// ---- fx-spec/keys.mdx: the schema, top level + a lifecycle entry + each section
{
  let s = HEADER("spec/fx-spec-1.schema.json");
  const describe = (p) => esc(p.description ?? (p.$ref ? `see ${p.$ref.split("/").pop()}` : ""));
  const ty = (p) => (p.type ? [].concat(p.type).join(" \\| ") : p.$ref ? "object" : p.anyOf ? "object \\| null" : "");
  // 1.7 names only in the tables; the 1.x aliases get one line of their own
  // (readers copy what they see -- the orchestrator's review, 2026-09-19).
  const DEPRECATED_KEYS = new Set(["state"]); // the 1.0-1.6 name of `pattern`
  const current = (props) => Object.entries(props).filter(([k]) => !DEPRECATED_KEYS.has(k));
  s += "### Top level\n\n" + table(["Key", "Type", "Description"], current(schema.properties).map(([k, p]) => [code(k), ty(p), describe(p)]));
  s += "\n### A `states` entry\n\n" + table(["Key", "Type", "Description"], current(schema.$defs.stateEntry.properties).map(([k, p]) => [code(k), ty(p), describe(p)]));
  s += "\n### A binding\n\n" + table(["Key", "Type", "Description"], Object.entries(schema.$defs.binding.properties).map(([k, p]) => [code(k), ty(p), describe(p)]));
  const aliasOf = new Map();
  for (const d of Object.values(defs)) for (const a of d.aliases ?? []) aliasOf.set(a, d.type === "number[]" ? `${d.path}[${a.replace(/\D+/g, "")}]` : d.path);
  const targets = schema.$defs.bindings.propertyNames.enum;
  s += `\nBindable targets: ${targets.filter((t) => !aliasOf.has(t)).map(code).join(", ")}.\n`;
  s += `\nDeprecated aliases (FX Spec 1.6 and earlier; still accepted, with a warning in a 1.7 file): ${code("state")} → ${code("pattern")}, ${targets.filter((t) => aliasOf.has(t)).map((t) => `${code(t)} → ${code(aliasOf.get(t))}`).join(", ")}. See the [rename map](/docs/reference/migration#what-was-renamed).\n`;
  for (const sec of ["colorSection", "gradient", "glow", "noise", "pulse", "liquid", "particles", "holographic", "performance"]) {
    const d = schema.$defs[sec];
    if (!d?.properties) continue;
    const title = { colorSection: "color", gradient: "gradient", performance: "performance" }[sec] ?? `materials.${sec}`;
    s += `\n### \`${title}\`\n\n` + table(
      ["Key", "Type", "Range", "Description"],
      Object.entries(d.properties).map(([k, p]) => [
        code(k),
        ty(p) || (p.enum ? "enum" : ""),
        p.enum ? p.enum.map(code).join(" · ") : p.minimum !== undefined ? `${num(p.minimum)}–${num(p.maximum)}` : "",
        describe(p),
      ]),
    );
  }
  files.set("fx-spec/keys.mdx", s);
}

// ---- fx-spec/rename-map.mdx: FX Spec 1.7 names vs the 1.x names they replace
{
  let s = HEADER("spec/parameters.json + spec/fx-spec-1.schema.json");
  const rows = [
    [code('"state"') + " (the look, top level and in " + code("states.*") + ")", code('"pattern"'), "FX Spec file"],
    [code("specState") + " (SinuaView)", code("state"), "view API"],
    [code("state") + " (SinuaView, plain input)", code("pattern"), "view API"],
  ];
  for (const d of Object.values(defs)) {
    for (const a of d.aliases ?? []) {
      const target = d.type === "number[]" ? `${code(d.path + "[" + a.replace(/\D+/g, "") + "]")}` : code(d.path);
      rows.push([code(a) + " (binding target)", target, "FX Spec bindings"]);
    }
  }
  rows.push([code("progress0..3") + " / " + code("segment0..23") + " in " + code("params"), code('"progress": [..]') + " / " + code('"segment": [..]'), "FX Spec params"]);
  s += table(["1.0–1.6 name", "1.7 name", "Where"], rows);
  files.set("fx-spec/rename-map.mdx", s);
}

// ---- diagnostics.mdx: the engine's real output for each curated trigger
{
  let s = HEADER("scripts/docs/diagnostics-cases.json, run through the engine");
  const rows = [];
  for (const c of cases.spec) {
    const r = resolveFxSpec(JSON.stringify(c.spec), c.state ? { state: c.state } : {});
    for (const d of r.diagnostics) rows.push([esc(c.title), d.severity === "error" ? "**error**" : "warning", code(d.path || "/"), esc(d.message)]);
  }
  s += "### In an FX Spec\n\n" + table(["Case", "Severity", "Path", "Message"], rows);
  const orows = [];
  for (const c of cases.overrides) {
    for (const d of checkOverrides(c.pattern, c.size, c.overrides)) orows.push([esc(c.title), d.severity, code(d.path), esc(d.message)]);
  }
  s += "\n### In overrides (`checkOverrides`)\n\n" + table(["Case", "Severity", "Path", "Message"], orows);
  files.set("diagnostics.mdx", s);
}

// ---- write or check
let stale = [];
const want = new Set([...files.keys()].map((k) => join(OUT, k)));
for (const [rel, text] of files) {
  const p = join(OUT, rel);
  const cur = existsSync(p) ? readFileSync(p, "utf8") : null;
  if (cur !== text) {
    stale.push(relative(root, p));
    if (!check) {
      mkdirSync(dirname(p), { recursive: true });
      writeFileSync(p, text);
    }
  }
}
// Files that shouldn't exist anymore.
const walk = (d) => (existsSync(d) ? readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)])) : []);
for (const p of walk(OUT)) {
  if (!want.has(p)) {
    stale.push(relative(root, p) + " (orphan)");
    if (!check) rmSync(p);
  }
}
if (check) {
  if (stale.length) {
    console.error(`docs partials are stale -- run \`node scripts/docs/gen.mjs\`:\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`docs partials up to date (${files.size} files)`);
} else {
  console.log(`wrote ${stale.length} of ${files.size} partials`);
}
